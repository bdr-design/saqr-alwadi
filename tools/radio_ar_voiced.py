def num(n):
  if n < 10: return U[n]
  if n < 20: return TEEN[n]
  return T[n // 10] if n % 10 == 0 else U[n % 10] + ' و' + T[n // 10]
# the hundreds: ending "-at" before مِتْرْ ("khamsimyat mitr", written with its t: as ةْ it took a case ending), "-a"
# before و ("khamsimya w-khamsin")
HUND = ['', 'مِيَّ', 'مِيتَيْنْ', 'ثَلاثْمِيَّ', 'أَرْبَعْمِيَّ', 'خَمْسْمِيَّ', 'سِتّْمِيَّ', 'سَبْعْمِيَّ', 'ثَمانْمِيَّ', 'تِسْعْمِيَّ']
def dist(d):
  th, r = divmod(d, 1000); h, r = divmod(r, 100)
  hund = HUND[h] + ('' if h == 2 or not h else 'هْ' if r else 'تْ')
  parts = [x for x in ([{1: 'أَلْفْ', 2: 'أَلْفَيْنْ', 3: 'ثَلاثْ آلافْ'}.get(th, '')] + [hund] + [num(r) if r else '']) if x]
  return ' و'.join(parts) + ' مِتْرْ'
