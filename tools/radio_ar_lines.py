U = ['', 'واحد', 'اثنين', 'ثلاثة', 'أربعة', 'خمسة', 'ستة', 'سبعة', 'ثمانية', 'تسعة']
TEEN = {10: 'عشر', 11: 'احدعش', 12: 'اثنعش', 13: 'ثلطعش', 14: 'أربعطعش', 15: 'خمسطعش', 16: 'ستطعش', 17: 'سبعطعش', 18: 'ثمنطعش', 19: 'تسعطعش'}
T = ['', '', 'عشرين', 'ثلاثين', 'أربعين', 'خمسين', 'ستين', 'سبعين', 'ثمانين', 'تسعين']
def num(n):
  if n < 10: return U[n]
  if n < 20: return TEEN[n]
  return T[n // 10] if n % 10 == 0 else U[n % 10] + ' و' + T[n // 10]
HUND = ['', 'مية', 'ميتين', 'ثلاثمية', 'أربعمية', 'خمسمية', 'ستمية', 'سبعمية', 'ثمانمية', 'تسعمية']
def dist(d):
  th, r = divmod(d, 1000); h, r = divmod(r, 100)
  parts = [x for x in ([{1: 'ألف', 2: 'ألفين', 3: 'ثلاثة آلاف'}.get(th, '')] + [HUND[h]] + [num(r) if r else '']) if x]
  return ' و'.join(parts) + ' متر'
